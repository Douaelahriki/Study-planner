/**
 * @desc    Créer une session manuellement
 * @route   POST /api/sessions
 * @access  Private
 */
const createSession = async (req, res, next) => {
  try {
    const { subjectId, title, date, startTime, endTime, notes } = req.body;

    // Validation
    if (!subjectId || !date || !startTime || !endTime) {
      return res.status(400).json({
        success: false,
        message: 'Champs obligatoires : subjectId, date, startTime, endTime'
      });
    }

    // Vérifier que la matière existe et appartient à l'user
    const subject = await Subject.findOne({
      _id: subjectId,
      userId: req.user._id
    });

    if (!subject) {
      return res.status(404).json({
        success: false,
        message: 'Matière non trouvée ou non autorisée'
      });
    }

    // Calculer la durée
    const duration = timeToMinutes(endTime) - timeToMinutes(startTime);
    
    if (duration <= 0) {
      return res.status(400).json({
        success: false,
        message: 'L\'heure de fin doit être après l\'heure de début'
      });
    }

    if (duration < 15) {
      return res.status(400).json({
        success: false,
        message: 'La durée minimale est de 15 minutes'
      });
    }

    // Vérifier la durée max de la matière
    if (duration > subject.maxSessionDuration) {
      return res.status(400).json({
        success: false,
        message: `Durée trop longue. Max pour cette matière : ${subject.maxSessionDuration}min`
      });
    }

    // Vérifier les chevauchements
    const sessionsOnSameDay = await Session.find({
      userId: req.user._id,
      date: new Date(date),
      status: { $ne: 'cancelled' }
    });

    const newSession = { date, startTime, endTime };
    const overlap = sessionsOnSameDay.find(s => hasOverlap(s, newSession));

    if (overlap) {
      return res.status(400).json({
        success: false,
        message: `Cette session chevauche une session existante (${overlap.startTime} - ${overlap.endTime})`
      });
    }

    // Créer la session
    const session = await Session.create({
      userId: req.user._id,
      subjectId,
      title: title || `Session de ${subject.name}`,
      date: new Date(date),
      startTime,
      endTime,
      duration,
      notes: notes || '',
      isAutoGenerated: false
    });

    await session.populate('subjectId', 'name color priority');

    res.status(201).json({
      success: true,
      message: 'Session créée avec succès',
      session
    });
  } catch (error) {
    next(error);
  }
};

/**
 * @desc    Modifier une session
 * @route   PUT /api/sessions/:id
 * @access  Private
 */
const updateSession = async (req, res, next) => {
  try {
    const session = await Session.findOne({
      _id: req.params.id,
      userId: req.user._id
    });

    if (!session) {
      return res.status(404).json({
        success: false,
        message: 'Session non trouvée'
      });
    }

    const { title, date, startTime, endTime, notes, subjectId } = req.body;

    // Si on change l'heure, recalculer la durée
    if (startTime || endTime) {
      const newStart = startTime || session.startTime;
      const newEnd = endTime || session.endTime;
      const duration = timeToMinutes(newEnd) - timeToMinutes(newStart);
      
      if (duration <= 0) {
        return res.status(400).json({
          success: false,
          message: 'L\'heure de fin doit être après l\'heure de début'
        });
      }
      
      session.duration = duration;
      if (startTime) session.startTime = startTime;
      if (endTime) session.endTime = endTime;
    }

    if (title !== undefined) session.title = title;
    if (date !== undefined) session.date = new Date(date);
    if (notes !== undefined) session.notes = notes;
    if (subjectId !== undefined) session.subjectId = subjectId;

    await session.save();
    await session.populate('subjectId', 'name color priority');

    res.json({
      success: true,
      message: 'Session mise à jour',
      session
    });
  } catch (error) {
    next(error);
  }
};

