const Session = require('../models/Session');
const Subject = require('../models/Subject');

/**
 * Helper : convertir HH:MM en minutes
 */
const timeToMinutes = (time) => {
  const [hours, minutes] = time.split(':').map(Number);
  return hours * 60 + minutes;
};

/**
 * Helper : vérifier le chevauchement
 */
const hasOverlap = (session1, session2) => {
  const date1 = new Date(session1.date).toDateString();
  const date2 = new Date(session2.date).toDateString();
  if (date1 !== date2) return false;
  
  const start1 = timeToMinutes(session1.startTime);
  const end1 = timeToMinutes(session1.endTime);
  const start2 = timeToMinutes(session2.startTime);
  const end2 = timeToMinutes(session2.endTime);
  
  return start1 < end2 && start2 < end1;
};

/**
 * @desc    Récupérer toutes les sessions de l'utilisateur
 * @route   GET /api/sessions
 * @access  Private
 */
const getMySessions = async (req, res, next) => {
  try {
    const { status, startDate, endDate, subjectId } = req.query;
    
    const filter = { userId: req.user._id };
    
    if (status) filter.status = status;
    if (subjectId) filter.subjectId = subjectId;
    if (startDate || endDate) {
      filter.date = {};
      if (startDate) filter.date.$gte = new Date(startDate);
      if (endDate) filter.date.$lte = new Date(endDate);
    }
    
    const sessions = await Session.find(filter)
      .populate('subjectId', 'name color priority')
      .sort({ date: 1, startTime: 1 });

    res.json({
      success: true,
      count: sessions.length,
      sessions
    });
  } catch (error) {
    next(error);
  }
};

