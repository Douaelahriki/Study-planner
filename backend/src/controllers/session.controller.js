/**
 * @desc    Statistiques des sessions
 * @route   GET /api/sessions/stats
 * @access  Private
 */
const getSessionsStats = async (req, res, next) => {
  try {
    const total = await Session.countDocuments({ userId: req.user._id });
    const planned = await Session.countDocuments({ 
      userId: req.user._id, 
      status: 'planned' 
    });
    const completed = await Session.countDocuments({ 
      userId: req.user._id, 
      status: 'completed' 
    });
    const missed = await Session.countDocuments({ 
      userId: req.user._id, 
      status: 'missed' 
    });

    // Heures totales étudiées
    const completedSessions = await Session.find({ 
      userId: req.user._id, 
      status: 'completed' 
    });
    const totalMinutes = completedSessions.reduce(
      (sum, s) => sum + (s.actualDuration || s.duration), 0
    );

    res.json({
      success: true,
      stats: {
        total,
        planned,
        completed,
        missed,
        totalMinutes,
        totalHours: Math.round(totalMinutes / 60 * 10) / 10,
        completionRate: total > 0 ? Math.round((completed / total) * 100) : 0
      }
    });
  } catch (error) {
    next(error);
  }
};
